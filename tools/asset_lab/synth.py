"""Synthetic DDS families for unit tests and ``run`` scenarios (redistributable, no game data)."""
import struct

from . import dds

FORMATS = {'BC1': 71, 'BC1_SRGB': 72, 'BC3': 77, 'BC3_SRGB': 78, 'BC5': 83, 'BC7': 98, 'BC7_SRGB': 99,
           'R16G16B16A16_FLOAT': 10, 'R8G8B8A8': 28}


def header(width, height, dxgi, mips, split=False, cube=False):
    out = bytearray(148)
    out[:4] = b'DDS '
    struct.pack_into('<7I', out, 4, 124, 0x2100F, height, width, 0, 0, mips)
    if split: struct.pack_into('<I', out, 36, dds.SPLIT)
    struct.pack_into('<I', out, 76, 32)
    struct.pack_into('<I', out, 80, 4)
    out[84:88] = b'DX10'
    struct.pack_into('<I', out, 108, 0x1000)
    struct.pack_into('<5I', out, 128, dxgi, 3, 4 if cube else 0, 6 if cube else 1, 0)
    return out


def make_family(width, height, fmt='BC7', mips=None, streamed=0, payload=True):
    """Return ``{suffix: bytes}`` ('' is the base). ``streamed`` mips are split into ``.N`` parts.

    ``payload=False`` returns a header-only base, the shape of a file that claims more than it holds.
    """
    dxgi = FORMATS[fmt]
    mips = mips or max(width, height).bit_length()
    head = header(width, height, dxgi, mips, split=bool(streamed))
    sizes = dds.parse_header(bytes(head))['sizes']
    if not payload: return {'': bytes(head)}
    members = {'': bytes(head) + bytes(sum(sizes[streamed:]))}
    for n in range(1, streamed + 1): members[str(n)] = bytes(sizes[streamed - n])
    return members


def blobs(path, family):
    """Archive member names for a family generated by ``make_family``."""
    return {path + ('.' + suffix if suffix else ''): data for suffix, data in family.items()}
